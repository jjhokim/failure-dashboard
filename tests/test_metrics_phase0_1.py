"""
Phase 0-1 지표 정정 검증 테스트.

대상 함수 (backend/crud.py):
  - 고유가용도_Ai_계산  (알려진 오류 #1 정정: Ao → Ai)
  - MTTR_계산
  - 제대별_MTTR          (제대별 분리 + 완료/미완료 병기)
  - KPI_요약             (키 가용도_Ai, MTTR_완료건수)

손계산 가능한 소규모 고정 입력으로 기대값을 검증한다.
지표 함수의 backend/metrics.py 이전은 Phase 0-4 예정 (여기서는 crud.py 대상).
"""

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from backend.crud import (  # noqa: E402
    KPI_요약,
    MTTR_계산,
    고유가용도_Ai_계산,
    제대별_MTTR,
)


def _df(rows: list[dict]) -> pd.DataFrame:
    """고장이력_전체조회() 출력과 동일한 컬럼 구조의 소규모 DataFrame."""
    cols = ["발생일시", "제대구분", "처리상태", "수리소요시간_h"]
    return pd.DataFrame(rows, columns=cols)


# ---------------------------------------------------------------------------
# 고유가용도_Ai_계산  (Ai = MTBF / (MTBF + MTTR))
# ---------------------------------------------------------------------------

def test_ai_정상():
    # 90 / (90 + 10) = 0.9
    assert 고유가용도_Ai_계산(90.0, 10.0) == 0.9


def test_ai_mttr_none():
    # MTTR 없음(수리완료 데이터 없음) → None (0으로 오계산 방지)
    assert 고유가용도_Ai_계산(100.0, None) is None


def test_ai_분모_0():
    # MTBF=0, MTTR=0 → 분모 0 → None
    assert 고유가용도_Ai_계산(0.0, 0.0) is None


# ---------------------------------------------------------------------------
# MTTR_계산  (수리완료 건 평균)
# ---------------------------------------------------------------------------

def test_mttr_완료건_평균():
    df = _df([
        {"발생일시": "2025-01-01 00:00:00", "제대구분": "부대정비", "처리상태": "수리완료", "수리소요시간_h": 2.0},
        {"발생일시": "2025-01-02 00:00:00", "제대구분": "부대정비", "처리상태": "수리완료", "수리소요시간_h": 4.0},
        {"발생일시": "2025-01-03 00:00:00", "제대구분": "부대정비", "처리상태": "미해결",   "수리소요시간_h": None},
    ])
    # (2 + 4) / 2 = 3.0, 미완료건 제외
    assert MTTR_계산(df) == 3.0


def test_mttr_완료건_없음():
    df = _df([
        {"발생일시": "2025-01-01 00:00:00", "제대구분": "부대정비", "처리상태": "미해결", "수리소요시간_h": None},
    ])
    assert MTTR_계산(df) is None


# ---------------------------------------------------------------------------
# 제대별_MTTR  (제대별 분리 + 완료/미완료 병기)
# ---------------------------------------------------------------------------

def test_제대별_mttr():
    df = _df([
        {"발생일시": "2025-01-01 00:00:00", "제대구분": "부대정비", "처리상태": "수리완료", "수리소요시간_h": 2.0},
        {"발생일시": "2025-01-02 00:00:00", "제대구분": "부대정비", "처리상태": "수리완료", "수리소요시간_h": 4.0},
        {"발생일시": "2025-01-03 00:00:00", "제대구분": "부대정비", "처리상태": "수리중",   "수리소요시간_h": None},
        {"발생일시": "2025-01-04 00:00:00", "제대구분": "야전정비", "처리상태": "수리완료", "수리소요시간_h": 6.0},
    ])
    result = 제대별_MTTR(df).set_index("제대구분")

    assert result.loc["부대정비", "MTTR_h"] == 3.0
    assert result.loc["부대정비", "완료건수"] == 2
    assert result.loc["부대정비", "미완료건수"] == 1
    assert result.loc["야전정비", "MTTR_h"] == 6.0
    assert result.loc["야전정비", "완료건수"] == 1
    assert result.loc["야전정비", "미완료건수"] == 0


def test_제대별_mttr_빈입력():
    result = 제대별_MTTR(_df([]))
    assert list(result.columns) == ["제대구분", "MTTR_h", "완료건수", "미완료건수"]
    assert result.empty


# ---------------------------------------------------------------------------
# KPI_요약  (키 가용도_Ai, MTTR_완료건수)
# ---------------------------------------------------------------------------

def test_kpi_요약_키():
    df = _df([
        {"발생일시": "2025-01-01 00:00:00", "제대구분": "부대정비", "처리상태": "수리완료", "수리소요시간_h": 2.0},
        {"발생일시": "2025-01-11 00:00:00", "제대구분": "부대정비", "처리상태": "미해결",   "수리소요시간_h": None},
    ])
    kpi = KPI_요약(df)

    # Ao → Ai 정정: 고유가용도는 가용도_Ai 키로 제공된다
    assert "가용도_Ai" in kpi
    # Phase 0-4: 가용도_Ao는 '운용가용도'(별도 의미)로 재도입됨.
    # 현재 MDT/ALDT 결측이므로 None이어야 한다 (억지 계산 금지).
    assert kpi["가용도_Ao"] is None
    assert kpi["총_고장건수"] == 2
    assert kpi["미완료_건수"] == 1
    assert kpi["MTTR_완료건수"] == 1
